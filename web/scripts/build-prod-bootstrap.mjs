#!/usr/bin/env node
// =============================================================================
// build-prod-bootstrap.mjs: combine every migration into one file for a
// brand-new database.
// =============================================================================
//
// WHY: prod launches as a fresh Supabase project (docs/PROD_LAUNCH_CHECKLIST.md,
// Grant 2026-10-20). Pasting 34 files one by one is slow and error-prone, so
// this writes supabase/prod_bootstrap.sql: all of supabase/migrations/*.sql in
// filename order, as ONE transaction. If any statement fails, nothing is
// applied and the database stays empty; fix and rerun.
//
// The 34 migration files stay the source of truth (they're how dev got here,
// and docs/MIGRATION_LEDGER.md tracks them). Never edit prod_bootstrap.sql by
// hand: change a migration, then rerun this script.
//
// What it changes while combining: each file's own top-level `begin;` /
// `commit;` lines are dropped, so the outer transaction is the only one.
// Nothing else is altered.
//
// ONLY for an EMPTY database. Running it on a database that already has the
// schema fails on the first `create type` (by design: nothing is applied).
//
// Run from web/:   node scripts/build-prod-bootstrap.mjs
// Check only:      node scripts/build-prod-bootstrap.mjs --check
//                  (exits 1 if prod_bootstrap.sql is out of date)

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const migrationsDir = join(root, "supabase", "migrations");
const outPath = join(root, "supabase", "prod_bootstrap.sql");

const files = readdirSync(migrationsDir)
  .filter((f) => /^\d{14}_.+\.sql$/.test(f))
  .sort();

const TX_LINE = /^\s*(begin|commit)\s*;\s*(--.*)?$/i;

const sections = files.map((f) => {
  const raw = readFileSync(join(migrationsDir, f), "utf8").replace(/\r\n/g, "\n");
  const body = raw
    .split("\n")
    .filter((line) => !TX_LINE.test(line))
    .join("\n")
    .trimEnd();
  const sha = createHash("sha256").update(raw).digest("hex").slice(0, 12);
  return { f, sha, body };
});

const out = [
  "-- =============================================================================",
  "-- prod_bootstrap.sql: GENERATED by web/scripts/build-prod-bootstrap.mjs.",
  "-- Do not edit by hand; change a migration and rerun the script.",
  "-- =============================================================================",
  "--",
  `-- All ${files.length} files in supabase/migrations/, in order, as ONE transaction.`,
  "-- For an EMPTY database only (the fresh prod project): if anything fails,",
  "-- nothing is applied. See docs/PROD_LAUNCH_CHECKLIST.md step 2.",
  "--",
  "-- Sources (sha256 prefix of each file as combined):",
  ...sections.map((s, i) => `--   ${String(i + 1).padStart(2)}. ${s.f}  ${s.sha}`),
  "",
  "begin;",
  "",
  ...sections.flatMap((s, i) => [
    "-- #############################################################################",
    `-- ## ${i + 1}/${files.length}: ${s.f}`,
    "-- #############################################################################",
    "",
    s.body,
    "",
  ]),
  "commit;",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== out) {
    console.error("supabase/prod_bootstrap.sql is out of date. Run: node scripts/build-prod-bootstrap.mjs");
    process.exit(1);
  }
  console.log(`prod_bootstrap.sql is current (${files.length} migrations).`);
} else {
  writeFileSync(outPath, out);
  console.log(`Wrote supabase/prod_bootstrap.sql: ${files.length} migrations, ${(out.length / 1024).toFixed(0)} KB.`);
}
